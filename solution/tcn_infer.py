"""Inference of the dilated TCN in NumPy float64: no torch, the same arithmetic on every machine.

File structure
--------------
- export(): a trained model (the dict tcn_gpu.fit() returns) -> one .npz with its weights, scaling and
  column names. Called by the experiment scripts; the submission only reads the .npz.
- load(): the .npz as a dict.
- _conv1(), _conv3(), _stage(): 1x1 convolution, dilated 3-tap convolution (zero padding, as torch's
  Conv1d cross-correlation) and one stage (input conv, residual blocks, class head).
- forward(): softmax of the last stage for one scaled sequence (T, F).
- predict(): team-symmetric H/A/D probabilities of a match from its two feature views, block by block.
- predict_ensemble(): the arithmetic mean over several models, rounded to DECIMALS.
- match_probs(): the whole step for run.py --model tcn: the TCN input columns of a match, the model files
  of solution/models/, the ensemble's probabilities and the decoder weight.

Why not torch at inference. The submission must be regenerated byte for byte (RULES.md 3). A float32
network evaluated by torch gives results that depend on the device and the build. Here every operation is
a float64 matrix product or an elementwise function, about 1e-9 from the float32 training-time forward
pass, and the ensemble's probabilities are rounded to DECIMALS places before the decoder sees them, so
differences in the last bits between BLAS builds cannot move a label.

Used by run.py --model tcn, the default (the submitted model, K2).
"""

import os

import numpy as np

# Params
DECIMALS = 6      # probabilities are rounded to this many places before decoding
MODEL_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models")
MODEL_FILES = ("tcn_k2_s0.npz", "tcn_k2_s1.npz", "tcn_k2_s2.npz")   # candidate K2: k4_e10, seeds 0, 1, 2
GROUPS = ("ball", "near3", "near1")       # team_shape feature groups the TCN was trained with
DROP_SUFFIXES = ("_m25", "_m75")          # columns of the P3 feature set the TCN does not use
ALPHA = 0.75                              # decoder weight of the TCN's log-probabilities


def export(saved, path):
    """Write a trained model to `path` (.npz).

    Args:
        saved: dict with state (name -> tensor or array), mean, std, cols, p1_index, cfg.
        path: target file.
    """
    arrays = {"w:" + k: np.asarray(v, dtype=np.float32) for k, v in saved["state"].items() if k != "p1_index"}
    np.savez(path, mean=np.asarray(saved["mean"], dtype=np.float64), std=np.asarray(saved["std"], dtype=np.float64),
             cols=np.array(saved["cols"]), p1_index=np.asarray(saved["p1_index"], dtype=np.int64),
             dilations=np.asarray(saved["cfg"]["dilations"], dtype=np.int64),
             dilations2=np.asarray(saved["cfg"]["dilations2"], dtype=np.int64),
             stages=np.int64(saved["cfg"]["stages"]), **arrays)


def load(path):
    """The exported model: weights as float64 arrays under their state names, plus the scaling and columns."""
    with np.load(path) as z:
        out = {k: z[k] for k in z.files if not k.startswith("w:")}
        out["w"] = {k[2:]: z[k].astype(np.float64) for k in z.files if k.startswith("w:")}
    out["cols"] = [str(c) for c in out["cols"]]
    return out


def _conv1(x, weight, bias):
    """1x1 convolution of x (T, C_in) with weight (C_out, C_in, 1)."""
    return x @ weight[:, :, 0].T + bias


def _conv3(x, weight, bias, dilation):
    """3-tap dilated convolution with zero padding `dilation`: y[t] = W0 x[t-d] + W1 x[t] + W2 x[t+d] + b."""
    d = int(dilation)
    y = x @ weight[:, :, 1].T + bias
    if d < len(x):
        y[d:] += x[:-d] @ weight[:, :, 0].T
        y[:-d] += x[d:] @ weight[:, :, 2].T
    return y


def _stage(x, w, prefix, dilations):
    """One stage: returns the class logits (T, 3)."""
    h = _conv1(x, w[prefix + ".inp.weight"], w[prefix + ".inp.bias"])
    for i, d in enumerate(dilations):
        base = "{}.blocks.{}.".format(prefix, i)
        z = np.maximum(_conv3(h, w[base + "dilated.weight"], w[base + "dilated.bias"], d), 0.0)
        h = h + _conv1(z, w[base + "point.weight"], w[base + "point.bias"])
    return _conv1(h, w[prefix + ".out.weight"], w[prefix + ".out.bias"])


def _softmax(logits):
    e = np.exp(logits - logits.max(1, keepdims=True))
    return e / e.sum(1, keepdims=True)


def forward(model, x):
    """Class probabilities (T, 3) of the last stage for one scaled sequence x (T, F) float64."""
    w = model["w"]
    logits = _stage(x, w, "stage1", model["dilations"])
    p1 = x[:, model["p1_index"]]
    for i in range(int(model["stages"]) - 1):
        logits = _stage(np.concatenate((_softmax(logits), p1), axis=1), w, "refine.{}".format(i), model["dilations2"])
    return _softmax(logits)


def predict(model, x_home, x_swap, blocks):
    """Team-symmetric probabilities (N, 3): 0.5 * (P_home + swap(P_swap)) inside the blocks, 1/3 elsewhere.

    Args:
        model: load() output.
        x_home, x_swap: (N, F) feature matrices in the two team views, columns in model["cols"] order.
        blocks: [(half, first, last)].

    Returns:
        np.ndarray: (N, 3) float64, columns H, A, D.
    """
    views = []
    for x in (x_home, x_swap):
        scaled = np.nan_to_num((x.astype(np.float64) - model["mean"]) / model["std"], nan=0.0)
        scaled = scaled.astype(np.float32).astype(np.float64)    # the network was trained on float32 inputs
        out = np.full((len(x), 3), 1.0 / 3.0)
        for _, first, last in blocks:
            out[first:last + 1] = forward(model, scaled[first:last + 1])
        views.append(out)
    p = np.empty_like(views[0])
    p[:, 0] = 0.5 * (views[0][:, 0] + views[1][:, 1])
    p[:, 1] = 0.5 * (views[0][:, 1] + views[1][:, 0])
    p[:, 2] = 0.5 * (views[0][:, 2] + views[1][:, 2])
    return p


def predict_ensemble(models, x_home, x_swap, blocks):
    """Mean of the models' probabilities, rounded to DECIMALS places (see the module docstring)."""
    total = np.zeros((len(x_home), 3))
    for model in models:
        total += predict(model, x_home, x_swap, blocks)
    return np.round(total / len(models), DECIMALS)


def match_probs(f, blocks, ev):
    """The TCN ensemble's probabilities for one match.

    Args:
        f: feature dict with 'players', 'slot_team', 'pitch_length'.
        blocks: [(half, first, last)].
        ev: run.evidence() output.

    Returns:
        tuple: (probabilities (N, 3) float64, decoder weight alpha), or (None, None) when a model file
        is missing.
    """
    import learned
    import team_shape
    paths = [os.path.join(MODEL_DIR, name) for name in MODEL_FILES]
    if not all(os.path.isfile(p) for p in paths):
        return None, None
    models = [load(p) for p in paths]
    saved = team_shape.LOCAL_GROUPS
    team_shape.LOCAL_GROUPS = GROUPS
    try:
        names, x_home, x_swap = learned.match_inputs(f, blocks, ev)
    finally:
        team_shape.LOCAL_GROUPS = saved
    keep = [i for i, c in enumerate(names) if not c.endswith(DROP_SUFFIXES)]
    cols = [names[i] for i in keep]
    if any(m["cols"] != cols for m in models):
        raise ValueError("feature set changed since the TCN was trained; retrain and export it")
    return predict_ensemble(models, x_home[:, keep], x_swap[:, keep], blocks), ALPHA
